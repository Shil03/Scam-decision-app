"""Labelled synthetic scenario suite (tests/scenarios/scenarios.json), run over HTTP.

For every scenario this verifies, and records in reports/scenario-report.md:
expected vs actual decision, expected vs actual reason codes, ruleset version,
correlation ID, persistence behaviour, and whether the request was scored.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from app.services import decision_engine
from tests.support import ApiEnv, CallCounter, load_scenarios, scenario_body

BASE, SCENARIOS = load_scenarios()
REPORT_DIR = Path(__file__).resolve().parent.parent / "reports"
RESULTS: list[dict] = []


@pytest.fixture(scope="module", autouse=True)
def scenario_report():
    yield
    if not RESULTS:
        return
    REPORT_DIR.mkdir(exist_ok=True)
    (REPORT_DIR / "scenario-report.json").write_text(json.dumps(RESULTS, indent=2), encoding="utf-8")
    passed = sum(r["result"] == "PASS" for r in RESULTS)
    lines = [
        "# Scenario report",
        "",
        f"{passed}/{len(RESULTS)} scenarios passed. Generated by `tests/test_scenarios.py` from actual responses and database rows.",
        "",
        "| ID | Scenario | Expected | Actual | Expected reason codes | Actual reason codes | Ruleset | Correlation ID | Persisted | Scored | Result |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in RESULTS:
        lines.append(
            f"| {r['id']} | {r['name']} | {r['expected_decision']} | {r['actual_decision']} | "
            f"{', '.join(r['expected_reason_codes']) or '-'} | {', '.join(r['actual_reason_codes']) or '-'} | "
            f"{r['ruleset_version'] or '-'} | {'ok' if r['correlation_ok'] else 'MISMATCH'} | {r['persisted']} | "
            f"{'yes' if r['scored'] else 'no'} | {r['result']} |")
    (REPORT_DIR / "scenario-report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _deep_update(target: dict, changes: dict) -> None:
    for key, value in changes.items():
        if isinstance(value, dict) and isinstance(target.get(key), dict):
            _deep_update(target[key], value)
        else:
            target[key] = value


@pytest.mark.parametrize("sc", SCENARIOS, ids=[s["id"] for s in SCENARIOS])
def test_scenario(sc, tmp_path, monkeypatch):
    env = ApiEnv(tmp_path)
    if sc.get("config_changes"):
        env.edit_config(lambda d: _deep_update(d, sc["config_changes"]))
    active_version = env.active_ruleset_version()

    scorer = CallCounter(decision_engine.evaluate)
    monkeypatch.setattr(decision_engine, "evaluate", scorer)
    mule_service = env.app.state.shield.mule_service
    enricher = CallCounter(mule_service.check)
    monkeypatch.setattr(mule_service, "check", enricher)

    payment_id = f"PMT-{sc['id']}-0001"
    correlation_id = f"scn-{sc['id']}-corr-0001"
    response = env.client.post("/payments/assess", content=scenario_body(BASE, sc, payment_id),
                               headers={"Content-Type": "application/json", "X-Correlation-ID": correlation_id})
    body = response.json()
    expected = sc["expected"]
    is_reject = expected["decision"] == "REJECT"

    decisions = env.rows("SELECT * FROM decisions WHERE correlation_id = ?", (correlation_id,))
    queued = env.rows("SELECT * FROM review_queue WHERE payment_id = ?", (payment_id,))
    rejections = env.rows("SELECT * FROM rejections WHERE correlation_id = ?", (correlation_id,))
    persisted = "+".join(name for name, rows in (("decision", decisions), ("review_queue", queued),
                                                  ("rejection", rejections)) if rows) or "nothing"
    actual_codes = body.get("reason_codes", [])
    scored = scorer.calls > 0

    checks: dict[str, bool] = {
        "decision": body.get("decision") == expected["decision"],
        "correlation_id": body.get("correlation_id") == correlation_id
                          and response.headers.get("X-Correlation-ID") == correlation_id,
    }
    if is_reject:
        checks |= {
            "http_status": response.status_code in (413, 422),
            "error_fields": all(any(e["field"].startswith(f) for e in body.get("errors", []))
                                for f in expected["error_fields"]),
            "no_reason_codes_or_version": "reason_codes" not in body and "ruleset_version" not in body,
            "persisted_rejection_only": persisted == "rejection",
            "not_scored": scorer.calls == 0,
            "not_enriched": enricher.calls == 0,
        }
    else:
        row = decisions[0] if decisions else {}
        checks |= {
            "http_status": response.status_code == 200,
            "reason_codes": actual_codes == expected["reason_codes"],
            "at_least_one_reason": len(actual_codes) >= 1,
            "ruleset_version": body.get("ruleset_version") == active_version == row.get("ruleset_version"),
            "persisted_reason_codes": json.loads(row.get("reason_codes", "[]")) == expected["reason_codes"],
            "persisted_correlation_id": row.get("correlation_id") == correlation_id,
            "queued_iff_hold": bool(queued) == (expected["decision"] == "HOLD")
                               and (body.get("review_id") is not None) == (expected["decision"] == "HOLD"),
            "persistence": persisted == ("decision+review_queue" if expected["decision"] == "HOLD" else "decision"),
            "scored_once": scorer.calls == 1,
            "enriched_once": enricher.calls == 1,
            "customer_confirmation_iff_warn":
                body.get("requires_customer_confirmation") == (expected["decision"] == "WARN"),
        }
        if "scam_category" in expected:
            checks["scam_category"] = body.get("scam_category") == expected["scam_category"]
        if "degraded" in expected:
            checks["degraded"] = body.get("degraded") == expected["degraded"]

    failed = [name for name, ok in checks.items() if not ok]
    RESULTS.append({
        "id": sc["id"], "name": sc["name"],
        "expected_decision": expected["decision"], "actual_decision": body.get("decision"),
        "expected_reason_codes": expected.get("reason_codes", []), "actual_reason_codes": actual_codes,
        "ruleset_version": body.get("ruleset_version"), "correlation_ok": checks["correlation_id"],
        "persisted": persisted, "scored": scored, "http_status": response.status_code,
        "result": "FAIL" if failed else "PASS", "failed_checks": failed,
    })
    assert not failed, f"{sc['id']} failed checks {failed}; response={body}"
